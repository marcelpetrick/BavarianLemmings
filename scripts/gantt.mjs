/**
 * gantt.mjs: generate the roadmap Gantt chart in plan.md from the task list ("dashboards follow the
 * data", AGENTS.md). One bar per milestone heading `## Mx: title`:
 * - a milestone with no open task is drawn as done;
 * - an open milestone gets HOURS_PER_TASK hours per open task, chained one after another from the
 *   date in the plan's "Last update: YYYY-MM-DD" line.
 * The chart sits between the markers `<!-- gantt:start -->` and `<!-- gantt:end -->`.
 *
 * Usage:      node scripts/gantt.mjs [--write | --check]
 *               --write  rewrite the chart in plan.md (scripts/commit.sh does this before every commit)
 *               --check  fail when the chart in plan.md is not the generated one (pipeline)
 *               (none)   print the generated chart
 * Exit codes: 0 = written, up to date or printed, 1 = out of date (--check) or markers missing
 */
import { readFileSync, writeFileSync } from 'node:fs';

/** Agent effort per open task, in hours: a rough average over code, level and document tasks. */
const HOURS_PER_TASK = 0.3;
const START = '<!-- gantt:start -->';
const END = '<!-- gantt:end -->';

const plan = readFileSync('plan.md', 'utf8');
const date = /Last update: (\d{4}-\d{2}-\d{2})/.exec(plan)?.[1] ?? '2026-10-11';

const milestones = [];
let current = null;
for (const line of plan.split('\n')) {
  const heading = /^## (M\d+): (.+?)(?: \(.*\))?$/.exec(line);
  if (heading) {
    current = { id: heading[1], title: heading[2], done: 0, open: 0 };
    milestones.push(current);
  } else if (current && /^- \[x\] /.test(line)) current.done += 1;
  else if (current && /^- \[ \] /.test(line)) current.open += 1;
}

const lines = [
  '```mermaid',
  'gantt',
  '    title BavarianLemmings roadmap (generated by scripts/gantt.mjs)',
  '    dateFormat  YYYY-MM-DD',
  '    axisFormat  %d.%m.',
];
let previous = null;
for (const m of milestones) {
  const id = m.id.toLowerCase();
  const label = `${m.id} ${m.title} (${m.done}/${m.done + m.open})`.replace(/:/g, ' ');
  lines.push(`    section ${m.id}`);
  if (m.open === 0) lines.push(`    ${label} :done, ${id}, ${date}, 1d`);
  else {
    const hours = Math.max(1, Math.ceil(m.open * HOURS_PER_TASK));
    lines.push(`    ${label} :active, ${id}, ${previous ? `after ${previous}` : date}, ${hours}h`);
    previous = id;
  }
}
lines.push('```');
const chart = lines.join('\n');

const mode = process.argv[2];
if (!mode) {
  console.log(chart);
  process.exit(0);
}
const start = plan.indexOf(START);
const end = plan.indexOf(END);
if (start < 0 || end < start) {
  console.error(`plan.md lacks the markers ${START} and ${END}`);
  process.exit(1);
}
const updated = `${plan.slice(0, start + START.length)}\n\n${chart}\n\n${plan.slice(end)}`;
if (mode === '--check') {
  if (updated !== plan) {
    console.error('the Gantt chart in plan.md is out of date: run node scripts/gantt.mjs --write');
    process.exit(1);
  }
  console.log('Gantt chart up to date');
} else {
  writeFileSync('plan.md', updated);
  console.log('Gantt chart written');
}

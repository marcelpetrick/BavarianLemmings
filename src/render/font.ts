/** The glyph rows of one character; characters the font lacks fall back to `?`. */
export function glyphFor(character: string): readonly string[] {
  const glyph = FONT.glyphs[character] ?? FONT.glyphs[FALLBACK_CHARACTER];
  /* v8 ignore next -- the fallback glyph always exists; this guard only satisfies noUncheckedIndexedAccess */
  if (glyph === undefined) throw new Error('font has no fallback glyph');
  return glyph;
}

/** Width of a text in pixels: one cell per character (code point), so it includes the trailing gap. */
export function measureText(text: string): number {
  return Array.from(text).length * FONT.width;
}
